"""Build a schema-only local fixture from catalog snapshots; never contacts a database."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'test-results/masters-public-schema-only.json').read_text(encoding='utf-8'))
extra = json.loads((root / 'test-results/masters-public-schema-extra.json').read_text(encoding='utf-8'))
views = json.loads((root / 'test-results/masters-public-schema-views.json').read_text(encoding='utf-8'))
def ident(value):
    return '"' + value.replace('"', '""') + '"'

sql = ['begin;', 'create schema if not exists private;', 'grant usage on schema private to authenticated;']
for seq in extra['sequences'] or []:
    if any(seq['name'] in (c['default'] or '') for t in data['tables'] for c in t['columns']):
        sql.append(f"create sequence public.{ident(seq['name'])} as {seq['type']};")
for table in data['tables']:
    columns = []
    for col in table['columns']:
        definition = ident(col['name']) + ' ' + col['type']
        if col['identity']:
            definition += ' generated by default as identity'
        elif col['default']:
            definition += ' default ' + col['default']
        if col['notnull']:
            definition += ' not null'
        columns.append(definition)
    sql.append(f"create table public.{ident(table['name'])} ({','.join(columns)});")
for kind in ['PRIMARY KEY', 'UNIQUE', 'CHECK', 'FOREIGN KEY']:
    for table in data['tables']:
        for constraint in table['constraints'] or []:
            if constraint.startswith(kind):
                sql.append(f"alter table public.{ident(table['name'])} add {constraint};")
for view in views:
    options = ' with (' + ','.join(view['options']) + ')' if view['options'] else ''
    sql.append(f"create view public.{ident(view['name'])}{options} as {view['definition']};")
sql += [f + ';' for f in extra['functions'] or []]
sql += [f + ';' for f in data['functions'] or []]
sql += [i + ';' for i in extra['indexes'] or []]
sql += [t + ';' for t in data['triggers'] or []]
sql += ['CREATE TRIGGER trg_link_member_account AFTER INSERT OR UPDATE OF email ON auth.users FOR EACH ROW EXECUTE FUNCTION private.link_member_account();',
        'CREATE TRIGGER trg_promote_initial_admin AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION private.promote_initial_admin();']
for table in data['tables']:
    sql.append(f"revoke all on public.{ident(table['name'])} from PUBLIC, anon, authenticated, service_role;")
    if table['rls']:
        sql.append(f"alter table public.{ident(table['name'])} enable row level security;")
for policy in data['policies']:
    roles = ','.join('PUBLIC' if r == 'public' else ident(r) for r in policy['roles'])
    statement = f"create policy {ident(policy['policyname'])} on {ident(policy['schemaname'])}.{ident(policy['tablename'])} as {policy['permissive']} for {policy['cmd']} to {roles}"
    if policy['qual']:
        statement += ' using (' + policy['qual'] + ')'
    if policy['with_check']:
        statement += ' with check (' + policy['with_check'] + ')'
    sql.append(statement + ';')
for grant in data['grants']:
    sql.append(f"grant {grant['privilege_type']} on public.{ident(grant['table_name'])} to {ident(grant['grantee'])};")
for grant in extra['function_grants'] or []:
    signature = f"{ident(grant['schema'])}.{ident(grant['name'])}({grant['args']})"
    sql.append(f'revoke execute on function {signature} from PUBLIC;')
for grant in extra['function_grants'] or []:
    signature = f"{ident(grant['schema'])}.{ident(grant['name'])}({grant['args']})"
    role = 'PUBLIC' if grant['grantee'] == 'PUBLIC' else ident(grant['grantee'])
    sql.append(f'grant execute on function {signature} to {role};')
sql.append("insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types) values ('member-photos','member-photos',false,5242880,array['image/jpeg','image/png','image/webp']),('public-media','public-media',true,10485760,array['image/jpeg','image/png','image/webp','image/gif']),('club-memories','club-memories',false,10485760,array['image/jpeg','image/png','image/webp']);")
sql.append('commit; notify pgrst, \'reload schema\';')
output = root / 'test-results/masters-public-schema-baseline.sql'
output.write_text('\n'.join(sql), encoding='utf-8')
print(f'Schema-only fixture prepared: {len(data["tables"])} tables; no production rows.')
